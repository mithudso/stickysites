#!/usr/bin/env node
/** Deterministic text-only documentation inventory. No semantic index or embedding calls. */
import { execFileSync } from 'node:child_process';
import { existsSync, lstatSync, mkdirSync, readFileSync, realpathSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = realpathSync(path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..'));
const generated = new Set(['docs/high_signal_file_index.json', 'docs/codebase-overview.md', 'llms.txt', 'llms-full.txt', 'llms-small.txt', 'llms-facts.txt']);
const banner = '<!-- Generated by scripts/generate-docs.mjs; edit maintained sources, then run npm run docs:generate. -->\n';
const check = process.argv.includes('--check');
const compare = (a, b) => a < b ? -1 : a > b ? 1 : 0;
const escapeCell = (text) => String(text).replace(/\|/g, '\\|').replace(/[\r\n]+/g, ' ');
const link = (file) => file.split('/').map(encodeURIComponent).join('/');
const privateBody = (file) => /(?:^|\/)(?:memory\.md|prompts\.md|workflow[-_]logs?\.md|\.env(?:\.[^/]*)?|\.mcp\.json)$/.test(file) || /(?:^|\/)(?:\.codex|\.stele)\//.test(file) || /^(\.vscode\/.*mcp|docs\/archive\/)/.test(file);
function safeFile(file) {
  if (path.isAbsolute(file) || file.split('/').some((part) => part === '..') || /[\\\x00-\x1f]/.test(file)) return false;
  let full = root;
  for (const part of file.split('/')) {
    full = path.join(full, part);
    if (!existsSync(full) || lstatSync(full).isSymbolicLink()) return false;
  }
  return lstatSync(full).isFile();
}
function classification(file) {
  if (generated.has(file)) return 'generated text';
  if (/^(icons\/|store\/(screenshots|promo)\/)/.test(file)) return 'generated asset';
  if (/^docs\/superpowers\//.test(file)) return 'historical plan';
  if (/^docs\/archive\//.test(file)) return 'historical workflow archive';
  if (/^tests\/fixtures\/.*\.json$/.test(file)) return 'frozen fixture';
  if (privateBody(file)) return 'private operator context';
  if (/^docs\/.*(?:optimizer|audit|maintenance)[^/]*\d{4}-\d{2}-\d{2}[^/]*\.(?:md|json)$/.test(file)) return 'audit record';
  if (/^(tests\/|peer\/test_)/.test(file)) return 'maintained test';
  return 'maintained source';
}
function layer(file) {
  if (file.startsWith('tests/') || file.startsWith('peer/test_')) return 'test';
  if (file.startsWith('scripts/')) return 'tooling';
  if (file.startsWith('src/shared/')) return 'shared';
  if (file.startsWith('src/background/') || file.endsWith('.py')) return 'backend';
  if (/\.(js|css|html)$/.test(file)) return 'frontend';
  if (/\.md$/.test(file)) return 'documentation';
  return 'config';
}
const purposeOverrides = {
  'src/shared/settings.js': 'Shared preference normalization and integration deadlines for classic scripts and the worker.',
  'src/shared/network.js': 'Bound fetch headers and response-body reads with an abort deadline.',
  'src/shared/note-writer.js': 'Authoritative service-worker mutation queue, guarded sync commits, and storage readback verification.',
  'src/content/storage-content.js': 'Classic-script IPC client for the authoritative service-worker writer.',
  'src/content/safe-html.js': 'Inert rich-text allowlist sanitizer and block-aware plain-text extraction.',
  'tests/browser-integration.test.js': 'Synthetic DOM integration through manifest load order, all panel types, clips, vault and lock.',
  'tests/runtime-regressions.test.js': 'Actual browser-module regressions for vault, writer, panel ownership, mentions and drag behavior.',
  'tests/service-worker.test.js': 'Actual worker message/alarm integration with controlled sync completion.',
  'tests/sync-regressions.test.js': 'Synthetic delayed/malformed peer and native sync responses, conflicts and deadlines.',
  'tests/vault-legacy.test.js': 'Always-on decryption of frozen legacy corpus with real shared cryptographic primitives.',
  'tests/vault-import.test.js': 'Optional private-package absence versus installed import failure behavior.',
  'peer/peer_fixture.py': 'Disposable actual-daemon loopback fixture with isolated state, ephemeral ports and cleanup.',
  'manifest.json': 'Canonical Manifest V3 extension configuration, permissions, entry points, and version.',
  'package.json': 'Development dependencies, supported Node versions, and npm commands.',
  'package-lock.json': 'Locked development dependency graph.',
  'src/shared/crypto.js': 'ES-module cryptographic primitives used by tests and service-worker peer merging.',
  'scripts/build-store-zip.mjs': 'Build a runtime-only store ZIP from explicit regular files; exclude hidden paths and symlinks.',
  'scripts/check-doc-indexes.mjs': 'Validate the file inventory and required llms/wiki index links inside this repository.',
  'scripts/check-syntax.mjs': 'Check JavaScript syntax without following symlinks and enforce manifest/package version agreement.',
  'scripts/rotate-workflow-logs.mjs': 'Rotate whole Markdown sections with a cooperating lock, recoverable journal, and changed-snapshot refusal.',
  'scripts/harness-resources.mjs': 'Discover testing Chrome and manage owned browser, server, and temporary-directory resources with bounded shutdown.',
  'scripts/browser-checks.mjs': 'Screenshot readiness, owned UI actions, persisted site-body, and whole-bucket encryption/restoration checks.',
  'scripts/generate-docs.mjs': 'Generate and check deterministic text inventories, guide concatenation, abstracts, and source-backed facts.',
  'docs/external-calls.md': 'Document optional native messaging and loopback peer-daemon boundaries.',
  'docs/codebase-overview.md': 'Generated complete repository inventory grouped by directory.',
  'docs/high_signal_file_index.json': 'Generated per-file inventory with purpose, exported names, dependencies, and classification.',
  'llms.txt': 'Generated retrieval index linking inventoried repository files.',
  'llms-full.txt': 'Generated full text of selected maintained public guides; excludes private operator context.',
  'llms-small.txt': 'Generated short abstracts for selected maintained public guides.',
  'llms-facts.txt': 'Generated facts derived from manifest.json and package.json with source anchors.',
};
function abstract(body, fallback) {
  const paragraphs = body.replace(/<!--[^]*?-->/g, '').split(/\n\s*\n/);
  const paragraph = paragraphs.find((text) => text.trim() && !/^\s*(#|```|~~~|\||[-*] |\d+\. )/.test(text));
  if (!paragraph) return fallback;
  const text = paragraph.replace(/\s+/g, ' ').trim();
  // Abstracts are intentionally short; llms-full below retains complete source text.
  return text.length > 500 ? text.slice(0, 497) + '...' : text;
}

try {
  const configurationBodies = new Map();
  for (const config of ['manifest.json', 'package.json']) {
    if (!safeFile(config)) throw new Error(`Required configuration must be a regular file inside the repository: ${config}`);
    configurationBodies.set(config, readFileSync(path.join(root, config), 'utf8'));
  }
  // Never follow an output symlink, even when its target is missing. This also
  // protects the metadata read before generation or --check.
  for (const file of generated) {
    let full = root;
    for (const part of file.split('/')) {
      full = path.join(full, part);
      try { if (lstatSync(full).isSymbolicLink()) throw new Error(`Refusing generated output symlink: ${file}`); }
      catch (error) { if (error.code !== 'ENOENT') throw error; }
    }
  }
  const listed = execFileSync('git', ['ls-files', '--cached', '--others', '--exclude-standard', '-z'], { cwd: root, encoding: 'utf8', maxBuffer: 32 * 1024 * 1024 }).split('\0').filter(Boolean);
  const files = [...new Set([...listed.filter(safeFile), ...generated])].sort(compare);
  const fileSet = new Set(files);
  const previousPath = path.join(root, 'docs/high_signal_file_index.json');
  const previous = existsSync(previousPath) ? JSON.parse(readFileSync(previousPath, 'utf8')) : [];
  if (!Array.isArray(previous)) throw new Error('docs/high_signal_file_index.json metadata must be an array.');
  const metadata = new Map(previous.map((entry) => [entry.path, entry]));
  const bodies = new Map();
  for (const file of files) {
    if (generated.has(file) || privateBody(file)) continue;
    if (/\.(md|m?js|css|html|json|ya?ml|toml|txt)$/.test(file) || file === 'LICENSE') bodies.set(file, configurationBodies.get(file) ?? readFileSync(path.join(root, file), 'utf8'));
  }
  const entries = files.map((file) => {
    const old = metadata.get(file) ?? {};
    const body = bodies.get(file) ?? '';
    const fallback = /\.md$/.test(file) ? body.match(/^#\s+(.+)$/m)?.[1] ?? `Documentation: ${path.basename(file)}.` : `${classification(file)}: ${path.basename(file)}.`;
    let purpose = purposeOverrides[file] ?? old.purpose ?? fallback;
    if (file.startsWith('tests/')) purpose = purpose.replace(/^\d+ tests?(?: for [^:]+)?:?\s*/i, 'Tests: ');
    const existingExports = (old.exports ?? []).filter((symbol) => typeof symbol === 'string' && body.includes(symbol.split('.').at(-1)));
    const declaredExports = /\.m?js$/.test(file) ? [...body.matchAll(/\bexport\s+(?:async\s+)?(?:function|class|const|let|var)\s+([A-Za-z_$][\w$]*)/g)].map((match) => match[1]) : [];
    const dependencies = (old.depends_on ?? []).filter((dep) => fileSet.has(dep));
    for (const match of body.matchAll(/\b(?:from\s*|import\s*)['"](\.[^'"]+)['"]/g)) {
      const dependency = path.posix.normalize(path.posix.join(path.posix.dirname(file), match[1]));
      if (fileSet.has(dependency)) dependencies.push(dependency);
    }
    return {
      path: file, purpose, layer: old.layer ?? layer(file), classification: classification(file),
      lines: bodies.has(file) ? (body.match(/\n/g)?.length ?? 0) + (body && !body.endsWith('\n') ? 1 : 0) : null,
      exports: [...new Set([...existingExports, ...declaredExports])].sort(compare),
      depends_on: [...new Set(dependencies)].sort(compare), patterns: old.patterns ?? [],
    };
  });
  const guides = files.filter((file) => bodies.has(file) && /\.md$/.test(file) && classification(file) === 'maintained source' && (
    ['README.md', 'CONTRIBUTING.md', 'CODE_OF_CONDUCT.md', 'PRIVACY.md', 'peer/README.md'].includes(file) || file.startsWith('docs/') || file.startsWith('store/')
  ));
  const overview = [banner, '# Codebase overview\n', 'This complete inventory includes tracked files and nonignored new files. Generated files have no line count to avoid self-referential output. Private context is inventoried by path only. Historical plans and frozen fixtures are labeled.\n'];
  const groups = new Map();
  for (const entry of entries) {
    const directory = path.posix.dirname(entry.path);
    if (!groups.has(directory)) groups.set(directory, []);
    groups.get(directory).push(entry);
  }
  const llms = [banner, '# StickySites repository index\n', 'Generated from tracked and nonignored files. Use maintained guides for current behavior; historical plans describe earlier intent. Private operator context appears by path only.\n'];
  for (const [directory, group] of groups) {
    overview.push(`## ${directory === '.' ? 'Root' : `\`${directory}/\``}\n`, '| File | Lines | Classification | Purpose |\n|---|---:|---|---|');
    llms.push(`## ${directory === '.' ? 'Root' : directory}\n`);
    for (const entry of group) {
      overview.push(`| [${escapeCell(path.posix.basename(entry.path))}](${link(path.posix.relative('docs', entry.path))}) | ${entry.lines ?? '—'} | ${entry.classification} | ${escapeCell(entry.purpose)} |`);
      llms.push(`- [${entry.path}](${link(entry.path)}): ${entry.purpose} (${entry.classification})`);
    }
    overview.push(''); llms.push('');
  }
  const full = [banner, '# StickySites public guide text\n', 'Complete text of the selected maintained public guides follows. Workflow logs, archives, local agent/MCP configuration, and historical plans are excluded.\n'];
  const small = [banner, '# StickySites public guide abstracts\n'];
  for (const file of guides) {
    const body = bodies.get(file);
    full.push(`## Source: ${file}\n\n${body}${body.endsWith('\n') ? '' : '\n'}`);
    small.push(`## ${file}\n\n${abstract(body, metadata.get(file)?.purpose ?? path.basename(file))}\n`);
  }
  const manifest = JSON.parse(configurationBodies.get('manifest.json'));
  const pkg = JSON.parse(configurationBodies.get('package.json'));
  const facts = [banner, '# StickySites sourced configuration facts\n'];
  facts.push(`- The extension manifest version is ${manifest.manifest_version}; the extension version is ${manifest.version}. [src: manifest.json]`);
  facts.push(`- Declared permissions: ${(manifest.permissions ?? []).join(', ') || 'none'}. [src: manifest.json]`);
  for (const group of manifest.content_scripts ?? []) facts.push(`- Content-script JavaScript load order: ${(group.js ?? []).join(' → ') || 'none'}. [src: manifest.json]`);
  if (manifest.background) facts.push(`- The background entry is ${manifest.background.service_worker}; its type is ${manifest.background.type ?? 'classic'}. [src: manifest.json]`);
  if (manifest.action?.default_popup) facts.push(`- The browser-action popup is ${manifest.action.default_popup}. [src: manifest.json]`);
  if (pkg.engines?.node) facts.push(`- The supported Node version range is ${pkg.engines.node}. [src: package.json]`);
  for (const [name, command] of Object.entries(pkg.scripts ?? {}).sort(([a], [b]) => compare(a, b))) facts.push(`- npm run ${name} executes \`${command}\`. [src: package.json]`);
  facts.push(`- Declared development dependency names: ${Object.keys(pkg.devDependencies ?? {}).sort(compare).join(', ') || 'none'}. [src: package.json]`);
  const output = new Map([
    ['docs/high_signal_file_index.json', JSON.stringify(entries, null, 2) + '\n'],
    ['docs/codebase-overview.md', overview.join('\n') + '\n'],
    ['llms.txt', llms.join('\n') + '\n'], ['llms-full.txt', full.join('\n') + '\n'],
    ['llms-small.txt', small.join('\n') + '\n'], ['llms-facts.txt', facts.join('\n') + '\n'],
  ]);
  let drift = false;
  for (const [file, rendered] of output) {
    const text = rendered.replace(/\n+$/, '') + '\n';
    if (existsSync(path.join(root, file)) && readFileSync(path.join(root, file), 'utf8') === text) continue;
    if (check) { console.error(`Generated documentation drift: ${file}`); drift = true; }
    else {
      mkdirSync(path.dirname(path.join(root, file)), { recursive: true });
      writeFileSync(path.join(root, file), text);
      console.log(`Generated ${file}`);
    }
  }
  if (drift) process.exitCode = 1;
  else console.log(`${check ? 'Verified' : 'Inventoried'} ${entries.length} files and ${guides.length} complete public guides.`);
} catch (error) {
  console.error(`Documentation generation: ${error.message}`);
  process.exitCode = 1;
}
